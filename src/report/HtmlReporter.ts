import type { ProjectContext, ComponentContext } from "../context/ContextBuilder.js";
import { getReportCss, getReportJs } from "./template.js";

export interface ReportData {
  readonly project: ProjectContext;
  readonly generatedAt: string;
  readonly uxCoverage?: {
    readonly accessibility: number;
    readonly errorState: number;
    readonly loadingState: number;
    readonly responsive: number;
  };
}

// -----------------------------------------------------------------------------
// Public API
// -----------------------------------------------------------------------------

export function generateHtmlReport(data: ReportData): string {
  const css = getReportCss();
  const js = getReportJs();

  const summaryCards = renderSummaryCards(data);
  const depGraph = renderDependencyGraph(data);
  const componentTable = renderComponentTable(data);
  const insights = renderInsights(data);
  const uxCoverage = renderUxCoverage(data);

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>UIQuarter Report</title>
  <style>${css}</style>
</head>
<body>
  <div class="container">
    <h1>UIQuarter Report</h1>
    <p class="subtitle">Generated on ${escapeHtml(data.generatedAt)}</p>
    ${summaryCards}
    <h2>Dependency Graph</h2>
    ${depGraph}
    <h2>Components</h2>
    <input type="text" id="component-search" class="search" placeholder="Search components...">
    ${componentTable}
    <h2>Insights</h2>
    ${insights}
    ${uxCoverage}
    <footer>Generated by UIQuarter v0.1.0</footer>
  </div>
  <script src="https://cdn.jsdelivr.net/npm/mermaid@10/dist/mermaid.min.js"></script>
  <script>${js}</script>
</body>
</html>`;
}

